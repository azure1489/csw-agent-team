import json, os, sqlite3, sys

def load(db_path):
    db = sqlite3.connect(db_path)
    db.row_factory = sqlite3.Row
    wf = db.execute("SELECT * FROM workflows WHERE wf_key='daily_news' AND status='active'").fetchone()
    stages = [dict(r) for r in db.execute("SELECT * FROM workflow_stages WHERE workflow_id=? ORDER BY seq", (wf['id'],))]
    code = {s['id']: s['code'] for s in stages}
    seq = [s['code'] for s in stages]
    deps, gates = {}, {}
    for r in db.execute("SELECT stage_id, depends_on_id FROM workflow_stage_deps WHERE workflow_id=?", (wf['id'],)):
        deps.setdefault(code[r[0]], []).append(code[r[1]])
    for r in db.execute("SELECT stage_id, gate_order, reviewer_role, relayed_by_hub, name FROM workflow_gates WHERE workflow_id=? AND stage_id IS NOT NULL ORDER BY stage_id, gate_order", (wf['id'],)):
        gates.setdefault(code[r[0]], []).append({"reviewer": r[2], "relayed": bool(r[3]), "name": r[4]})
    for s in stages:
        s['deps'] = sorted(deps.get(s['code'], []), key=seq.index)
        s['gates'] = gates.get(s['code'], [])
    return {"workflow": {k: wf[k] for k in ("version", "dispatch_mode", "common_instructions", "common_acceptance")},
            "roles": {r[0]: r[1] for r in db.execute("SELECT code, name FROM roles")}, "stages": stages}

if len(sys.argv) != 3:
    sys.exit('用法：gen_stage_docs.py <已迁移的 sqlite 路径> <docs 目录>')
